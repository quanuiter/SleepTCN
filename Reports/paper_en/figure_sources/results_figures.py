# sequential blue ramp, light to dark (0% -> 100% of a reference row)
RAMP = ['F4F8FD', 'CDE2FB', '9EC5F4', '6DA7EC', '3987E5', '256ABF', '184F95', '104281']


def header(lang, comment):
    return (f'% {comment}\n% Generated by results_figures.py; values transcribed from locked tables.\n'
            '\\documentclass[tikz,border=4pt]{standalone}\n'
            f"{TEXT[lang]['preamble']}\n\\usepackage{{pgfplots}}\n\\pgfplotsset{{compat=1.18}}\n"
            f'\\usepgfplotslibrary{{groupplots}}\n{COLORS}\n\\begin{{document}}\n')


def ramp(percent):
    position = min(percent, 100) / 100 * (len(RAMP) - 1)
    low = int(position)
    high = min(low + 1, len(RAMP) - 1)
    t = position - low
    a, b = (tuple(int(c[i:i + 2], 16) for i in (0, 2, 4)) for c in (RAMP[low], RAMP[high]))
    return ''.join(f'{round(x + (y - x) * t):02X}' for x, y in zip(a, b))


def confusion(lang):
    s = TEXT[lang]
    cell = 0.92
    out = [header(lang, 'Row-normalised E3 confusion matrices, Sleep-EDF and first SHHS1 sample.'),
           '\\begin{tikzpicture}[font=\\small]']
    for panel, (title, matrix) in enumerate(((s['edf'], EDF), (s['shhs'], SHHS))):
        x0 = panel * 6.9
        out.append(f'\\node[anchor=south,font=\\small\\bfseries] at ({x0 + 2.5 * cell:.3f},{5 * cell + 0.55:.3f}) {{{title}}};')
        for i, row in enumerate(matrix):
            total = sum(row)
            y = (4 - i) * cell
            out.append(f'\\node[anchor=east] at ({x0 - 0.08:.3f},{y + cell / 2:.3f}) {{{STAGES[i]}}};')
            for j, count in enumerate(row):
                pct = 100 * count / total
                fill = ramp(pct)
                text = 'white' if pct >= 45 else 'ink'
                x = x0 + j * cell
                out.append(f'\\definecolor{{c{panel}{i}{j}}}{{HTML}}{{{fill}}}')
                out.append(f'\\fill[c{panel}{i}{j}] ({x + 0.02:.3f},{y + 0.02:.3f}) rectangle ({x + cell - 0.02:.3f},{y + cell - 0.02:.3f});')
                out.append(f'\\node[text={text},font=\\footnotesize] at ({x + cell / 2:.3f},{y + cell / 2:.3f}) {{{pct:.1f}}};')
        # outline the N3 -> N2 cell, the dominant transfer error
        x, y = x0 + 2 * cell, 1 * cell
        out.append(f'\\draw[stwo,line width=1.4pt] ({x + 0.02:.3f},{y + 0.02:.3f}) rectangle ({x + cell - 0.02:.3f},{y + cell - 0.02:.3f});')
        for j, stage in enumerate(STAGES):
            out.append(f'\\node[anchor=north] at ({x0 + (j + 0.5) * cell:.3f},-0.05) {{{stage}}};')
        out.append(f'\\node[anchor=north] at ({x0 + 2.5 * cell:.3f},-0.5) {{{s["predicted"]}}};')
        out.append(f'\\node[rotate=90,anchor=south] at ({x0 - 0.62:.3f},{2.5 * cell:.3f}) {{{s["reference"]}}};')
    out += ['\\end{tikzpicture}', '\\end{document}', '']
    return '\n'.join(out)


def interval_plot(color, mark, points, size='2.6pt', fill=True):
    style = f'{color},mark={mark},mark size={size},line width=0.9pt'
    if not fill:
        style += ',mark options={fill=white}'
    coords = ' '.join(f'({est},{y}) +- ({est - lo},{0})' if lo is None else
                      f'({est},{y}) -= ({est - lo},0) += ({hi - est},0)' for est, lo, hi, y in points)
    return (f'\\addplot[{style},only marks,error bars/.cd,x dir=both,x explicit,'
            f'error bar style={{line width=0.9pt}},error mark options={{rotate=90,mark size=2pt}}] '
            f'coordinates {{{coords}}};')


def holdout(lang):
    s = TEXT[lang]
    common = ('xmin=-0.025,xmax=0.062,grid=major,major grid style={gridc},axis line style={muted},'
              'tick label style={font=\\footnotesize},label style={font=\\small},'
              'title style={font=\\small\\bfseries},xtick={-0.02,0,0.02,0.04,0.06},'
              'x tick label style={/pgf/number format/fixed,/pgf/number format/precision=2},'
              'scaled x ticks=false,'
              'ytick style={draw=none}')
    out = [header(lang, 'Holdout confirmation forest plot with between-seed differences.'),
           '\\begin{tikzpicture}', '\\begin{groupplot}[group style={group size=1 by 2,vertical sep=1.25cm},'
           'width=13.2cm,scale only axis,' + common + ']']
    # panel a: three hypotheses, three estimates each
    labels = ','.join('{' + h + '}' for h in s['h'])
    out.append(f'\\nextgroupplot[title={{{s["panel_a"]}}},height=3.4cm,ymin=0.4,ymax=3.6,ytick={{3,2,1}},'
               f'yticklabels={{{labels}}},y dir=normal,legend style={{font=\\footnotesize,draw=none,fill=white,'
               'fill opacity=0.85,text opacity=1,at={(0.01,0.97)},anchor=north west,legend columns=1},'
               'legend cell align=left]')
    out.append('\\addplot[ink,line width=0.7pt,forget plot] coordinates {(0,0.4) (0,3.6)};')
    for (rows, color, mark, offset, name) in ((FIRST, 'muted', '*', 0.25, s['first']),
                                              (HOLD42, 'sone', 'square*', 0.0, s['hold42']),
                                              (HOLD123, 'stwo', 'diamond*', -0.25, s['hold123'])):
        points = [(e, lo, hi, 3 - k + offset) for k, (e, lo, hi) in enumerate(rows)]
        out.append(interval_plot(color, mark, points, '2.8pt' if mark == 'diamond*' else '2.4pt'))
        out.append(f'\\addlegendentry{{{{{name}}}}}')
    # panel b: between-seed differences and E4-E3
    rows = [(s['seedrow'].format(name), e, lo, hi) for name, e, lo, hi in SEEDS]
    rows += [(s['e4e3'].format(seed), e, lo, hi) for seed, e, lo, hi in E4E3]
    n = len(rows)
    ticks = ','.join(str(n - k) for k in range(n))
    tick_labels = ','.join('{' + r[0] + '}' for r in rows)
    out.append(f'\\nextgroupplot[title={{{s["panel_b"]}}},height=4.1cm,ymin=0.4,ymax={n + 0.6},'
               f'ytick={{{ticks}}},yticklabels={{{tick_labels}}},xlabel={{{s["delta"]}}}]')
    out.append(f'\\addplot[ink,line width=0.7pt,forget plot] coordinates {{(0,0.4) (0,{n + 0.6})}};')
    seed_points = [(e, lo, hi, n - k) for k, (_, e, lo, hi) in enumerate(rows[:4])]
    out.append(interval_plot('ink', '*', seed_points, '2.2pt'))
    out.append(f'\\addplot[ink,only marks,mark=o,mark size=2.4pt,line width=0.9pt] coordinates {{({rows[4][1]},{n - 4})}};')
    e4_points = [(e, lo, hi, n - 5 - k) for k, (_, e, lo, hi) in enumerate(rows[5:])]
    out.append(interval_plot('sthree', 'triangle*', e4_points, '2.8pt'))
    out += ['\\end{groupplot}', '\\end{tikzpicture}', '\\end{document}', '']
    return '\n'.join(out)


def amplitude(lang):
    s = TEXT[lang]
    xs = [1, 2, 3, 4, 5]
    common = ('width=6.9cm,height=5.6cm,scale only axis=false,ymin=0,ymax=1,xmin=0.5,xmax=7.0,'
              'xtick={1,2,3,4,5,6.5},xticklabels={$\\times$0.5,$\\times$0.75,$\\times$1,$\\times$1.5,$\\times$2,'
              + s['adabn'] + '},grid=major,major grid style={gridc},axis line style={muted},'
              'tick label style={font=\\footnotesize},label style={font=\\small},'
              'title style={font=\\small\\bfseries},'
              'legend style={font=\\footnotesize,draw=none,fill=white,fill opacity=0.85,text opacity=1},'
              'legend cell align=left')
    out = [header(lang, 'Amplitude sweep and AdaBN for E4 (seed 42) on the SHHS1 holdout sample.'),
           '\\begin{tikzpicture}', '\\begin{groupplot}[group style={group size=2 by 1,horizontal sep=1.3cm},'
           + common + f',xlabel={{{s["gain"]}}}]']

    def series(values, color, mark, name):
        line = ' '.join(f'({x},{v})' for x, v in zip(xs, values[:5]))
        return [f'\\addplot[{color},mark={mark},mark size=2.6pt,line width=1.2pt] coordinates {{{line}}};',
                f'\\addlegendentry{{{{{name}}}}}',
                f'\\addplot[{color},only marks,mark={mark},mark size=2.6pt,forget plot] coordinates {{(6.5,{values[5]})}};']

    separator = '\\draw[muted,dashed] (axis cs:5.75,0) -- (axis cs:5.75,1);'
    reference = '\\draw[muted,dotted,line width=0.8pt] (axis cs:3,0) -- (axis cs:3,1);'
    out.append(f'\\nextgroupplot[title={{{s["amp_a"]}}},ylabel={{{s["score"]}}},'
               'legend style={at={(0.5,-0.24)},anchor=north,legend columns=1}]')
    out += series(N3_TO_N2, 'stwo', 'square*', s['n3n2'])
    out += series(N3_RECALL, 'sone', '*', s['n3recall'])
    out += series(F1_N3, 'sthree', 'triangle*', s['f1n3'])
    out += [separator, reference]
    out.append(f'\\nextgroupplot[title={{{s["amp_b"]}}},legend style={{at={{(0.5,-0.24)}},anchor=north,legend columns=1}}]')
    out += series(F1_W, 'stwo', 'square*', s['f1w'])
    out += series(F1_REM, 'sone', '*', s['f1rem'])
    out += series(MF1, 'sthree', 'triangle*', s['mf1'])
    out += [separator, reference, '\\end{groupplot}', '\\end{tikzpicture}', '\\end{document}', '']
    return '\n'.join(out)


def main():
    for lang, folder, suffix in (('en', EN_OUT, '_en'), ('vi', VI_OUT, '_vi')):
        for name, build in (('confusion', confusion), ('holdout', holdout), ('amplitude', amplitude)):
            (folder / f'{name}{suffix}.tex').write_text(build(lang), encoding='utf8')


if __name__ == '__main__':
    main()
